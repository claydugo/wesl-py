import argparse
import json
import subprocess
from pathlib import Path
from urllib.request import urlopen

parser = argparse.ArgumentParser()
parser.add_argument("--check", action="store_true")
arguments = parser.parse_args()
project_directory = Path(__file__).resolve().parents[1]
metadata = json.loads(
    subprocess.check_output(
        ["cargo", "metadata", "--locked", "--all-features", "--format-version", "1"],  # noqa: S607
        cwd=project_directory,
        text=True,
    )
)
license_texts: dict[str, list[str]] = {}
downloads: dict[str, str] = {}
for package in sorted(
    metadata["packages"], key=lambda package: (package["name"], package["version"])
):
    if package["id"] in metadata["workspace_members"]:
        continue
    directory = Path(package["manifest_path"]).parent
    paths = {
        path
        for path in directory.rglob("*")
        if path.is_file()
        and path.name.lower().startswith(
            ("license", "licence", "copying", "copyright", "notice", "unlicense")
        )
    }
    if package["license_file"]:
        paths.add(directory / package["license_file"])
    sources = {
        path.relative_to(directory).as_posix(): path.read_text(encoding="utf-8")
        for path in sorted(paths)
    }
    if not sources and package["repository"] == (
        "https://github.com/wgsl-tooling-wg/wesl-rs"
    ):
        revision = json.loads(
            (directory / ".cargo_vcs_info.json").read_text(encoding="utf-8")
        )["git"]["sha1"]
        for filename in ("LICENSE-APACHE", "LICENSE-MIT"):
            url = (
                "https://raw.githubusercontent.com/wgsl-tooling-wg/wesl-rs/"
                f"{revision}/{filename}"
            )
            if url not in downloads:
                with urlopen(url, timeout=30) as response:  # noqa: S310
                    downloads[url] = response.read().decode("utf-8")
            sources[url] = downloads[url]
    if not sources:
        parser.error(f"License files are missing for {package['name']}.")
    for source, text in sources.items():
        license_texts.setdefault(text, []).append(
            f"{package['name']} {package['version']} ({package['license']})\n{source}"
        )

contents = (
    "Rust dependency licenses\n\n"
    "Generated by tools/update_licenses.py from Cargo.lock.\n"
    "This collection includes build dependencies and all target platforms.\n"
    "Each notice applies to the upstream files identified below.\n\n"
    + "\n\n".join(
        "=" * 78 + "\n" + "\n\n".join(sources) + "\n\n" + text
        for text, sources in license_texts.items()
    )
    + "\n"
)
path = project_directory / "licenses/RUST-DEPENDENCIES"
if arguments.check:
    if not path.is_file() or path.read_text(encoding="utf-8") != contents:
        parser.error("Run pixi run python tools/update_licenses.py to update licenses.")
else:
    path.write_text(contents, encoding="utf-8", newline="\n")
